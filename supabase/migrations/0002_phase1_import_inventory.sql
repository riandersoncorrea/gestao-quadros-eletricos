-- --- 2. Gerador de TAG no padrão oficial PRT_QD_XXXX / OFC_QD_XXXX ----------
-- Substitui o formato antigo (POR_QUADRO_0001). Deriva o próximo número do
-- maior já existente por prefixo, com lock para evitar corrida.
create or replace function public.next_panel_tag(p_site text)
returns text language plpgsql as $$
declare
  v_prefix text;
  v_max int;
begin
  v_prefix := case lower(p_site)
    when 'porto' then 'PRT'
    when 'oficina' then 'OFC'
    when 'pelotizacao' then 'PEL'  -- fora de escopo BT; mantido por compat
    else null end;
  if v_prefix is null then
    raise exception 'Site desconhecido: %', p_site;
  end if;
  perform pg_advisory_xact_lock(hashtext('panel_tag_' || v_prefix));
  select coalesce(max((regexp_replace(tag, '^[A-Z]+_QD_', ''))::int), 0)
    into v_max
    from public.electrical_panels
    where tag ~ ('^' || v_prefix || '_QD_[0-9]+$');
  return v_prefix || '_QD_' || lpad((v_max + 1)::text, 4, '0');
end;
$$;

-- Sequences do formato antigo não são mais usadas.
